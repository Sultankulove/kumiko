//! WASM plugins: a component of the `kumiko:plugin` WIT world, run in-process by the host
//! (spec, sections 13 and 16).
//!
//! ```ignore
//! use kumiko_plugin_sdk::wasm::{Plugin, PluginMain};
//! use serde_json::json;
//!
//! struct Hello;
//!
//! impl PluginMain for Hello {
//!     fn build() -> Plugin {
//!         Plugin::new().command("hello.say", |_ctx, args| Ok(json!({ "said": args })))
//!     }
//! }
//!
//! kumiko_plugin_sdk::export_wasm_plugin!(Hello);
//! ```
//!
//! Build with `cargo build --target wasm32-wasip2`; the result is the component the manifest's
//! `entry` points to. Calls into the host block the plugin until they return; the host refuses
//! calls that would re-enter the plugin.

use std::cell::RefCell;
use std::collections::HashMap;
use std::rc::Rc;

use serde::Serialize;
use serde::de::DeserializeOwned;
use serde_json::Value;

use kumiko_protocol::common::CommandCall;
use kumiko_protocol::methods::command::{
    ExecuteCommand, InvokeCommand, SetContext, SetContextParams,
};
use kumiko_protocol::methods::lifecycle::{
    Initialize, InitializeParams, InitializeResult, PluginCapabilities, Shutdown,
};
use kumiko_protocol::methods::service::{ServiceCall, ServiceCallParams, ServiceInvoke};
use kumiko_protocol::{ErrorCode, PROTOCOL_VERSION, Request, ResponseError};
use kumiko_types::{CommandId, InterfaceId, PluginId};

/// Bindings generated from `sdk/wit/kumiko-plugin`; used by [`export_wasm_plugin!`].
#[doc(hidden)]
#[allow(unsafe_code, clippy::all)] // Canonical ABI glue generated by wit-bindgen.
pub mod bindings {
    wit_bindgen::generate!({
        path: "../../wit/kumiko-plugin",
        world: "kumiko-plugin",
        pub_export_macro: true,
        export_macro_name: "__export_kumiko_plugin",
        default_bindings_module: "kumiko_plugin_sdk::wasm::bindings",
    });
}

use bindings::kumiko::plugin::host;
use bindings::kumiko::plugin::types::RpcError;

type CommandFn = Rc<dyn Fn(&Context, Vec<Value>) -> Result<Value, ResponseError>>;
type InterfaceFn = Rc<dyn Fn(&Context, PluginId, Value) -> Result<Value, ResponseError>>;

/// Implemented by the plugin: builds its handlers once, on the first call from the host.
pub trait PluginMain {
    fn build() -> Plugin;
}

/// A WASM plugin under construction.
#[derive(Default)]
pub struct Plugin {
    commands: HashMap<String, CommandFn>,
    interfaces: HashMap<(String, String), InterfaceFn>,
    capabilities: PluginCapabilities,
}

impl Plugin {
    pub fn new() -> Self {
        Self::default()
    }

    /// Handles a command contributed in the manifest.
    pub fn command(
        mut self,
        id: &str,
        handler: impl Fn(&Context, Vec<Value>) -> Result<Value, ResponseError> + 'static,
    ) -> Self {
        self.commands.insert(id.to_owned(), Rc::new(handler));
        self
    }

    /// Handles a method of an interface declared in `[[provides]]`.
    pub fn interface(
        mut self,
        interface: &str,
        method: &str,
        handler: impl Fn(&Context, PluginId, Value) -> Result<Value, ResponseError> + 'static,
    ) -> Self {
        self.interfaces
            .insert((interface.to_owned(), method.to_owned()), Rc::new(handler));
        self
    }

    /// Declares optional host-to-plugin methods the plugin handles.
    pub fn capabilities(mut self, capabilities: PluginCapabilities) -> Self {
        self.capabilities = capabilities;
        self
    }
}

/// What a handler gets: the handshake data and calls into the host.
#[derive(Clone)]
pub struct Context {
    init: Rc<InitializeParams>,
}

impl Context {
    pub fn plugin_id(&self) -> &PluginId {
        &self.init.plugin_id
    }

    /// Everything the host sent in `initialize`.
    pub fn params(&self) -> &InitializeParams {
        &self.init
    }

    /// Any plugin-to-host KPP request; methods the plugin has no permission for fail with
    /// `PermissionDenied`.
    pub fn call(&self, method: &str, params: Value) -> Result<Value, ResponseError> {
        match host::call(method, &params.to_string()) {
            Ok(json) => serde_json::from_str(&json).map_err(|error| {
                ResponseError::new(
                    ErrorCode::InternalError,
                    format!("host sent invalid JSON: {error}"),
                )
            }),
            Err(error) => Err(from_rpc_error(error)),
        }
    }

    fn request<R: Request>(&self, params: &R::Params) -> Result<R::Result, ResponseError> {
        let result = self.call(R::METHOD, to_value(params)?)?;
        from_value(result)
    }

    /// Runs any command: of the core, of this plugin or of another plugin.
    pub fn execute_command(
        &self,
        command: CommandId,
        args: Vec<Value>,
    ) -> Result<Value, ResponseError> {
        self.request::<ExecuteCommand>(&CommandCall { command, args })
    }

    /// Calls a method of an interface declared in `[[consumes]]`.
    pub fn call_interface(
        &self,
        interface: InterfaceId,
        method: impl Into<String>,
        params: Value,
    ) -> Result<Value, ResponseError> {
        self.request::<ServiceCall>(&ServiceCallParams {
            interface,
            method: method.into(),
            params,
        })
    }

    /// Sets a context key in the plugin's own namespace.
    pub fn set_context(&self, key: impl Into<String>, value: Value) -> Result<(), ResponseError> {
        self.request::<SetContext>(&SetContextParams {
            key: key.into(),
            value,
        })
    }
}

fn to_value(value: &impl Serialize) -> Result<Value, ResponseError> {
    serde_json::to_value(value)
        .map_err(|error| ResponseError::new(ErrorCode::InternalError, error.to_string()))
}

fn from_value<T: DeserializeOwned>(value: Value) -> Result<T, ResponseError> {
    serde_json::from_value(value)
        .map_err(|error| ResponseError::new(ErrorCode::InvalidParams, error.to_string()))
}

fn from_rpc_error(error: RpcError) -> ResponseError {
    ResponseError {
        code: error.code,
        message: error.message,
        data: error.data.and_then(|data| serde_json::from_str(&data).ok()),
    }
}

fn to_rpc_error(error: ResponseError) -> RpcError {
    RpcError {
        code: error.code,
        message: error.message,
        data: error.data.map(|data| data.to_string()),
    }
}

struct Runtime {
    plugin: Plugin,
    init: Option<Rc<InitializeParams>>,
}

thread_local! {
    static RUNTIME: RefCell<Option<Runtime>> = const { RefCell::new(None) };
}

/// Entry point of `plugin.handle`, called by the code [`export_wasm_plugin!`] generates.
#[doc(hidden)]
pub fn handle<P: PluginMain>(method: String, params: String) -> Result<String, RpcError> {
    let params: Value = serde_json::from_str(&params).map_err(|error| {
        to_rpc_error(ResponseError::new(ErrorCode::ParseError, error.to_string()))
    })?;
    dispatch::<P>(&method, params)
        .map(|value| value.to_string())
        .map_err(to_rpc_error)
}

fn dispatch<P: PluginMain>(method: &str, params: Value) -> Result<Value, ResponseError> {
    // Handlers are cloned out of the runtime before they run, so no borrow is held while the
    // plugin calls into the host.
    let (init, plugin_command, plugin_interface, capabilities) =
        RUNTIME.with_borrow_mut(|runtime| {
            let runtime = runtime.get_or_insert_with(|| Runtime {
                plugin: P::build(),
                init: None,
            });
            let command = |id: &str| runtime.plugin.commands.get(id).cloned();
            let (command_handler, interface_handler) = match method {
                InvokeCommand::METHOD => {
                    let id = params
                        .get("command")
                        .and_then(Value::as_str)
                        .unwrap_or_default();
                    (command(id), None)
                }
                ServiceInvoke::METHOD => {
                    let key = |field: &str| {
                        params
                            .get(field)
                            .and_then(Value::as_str)
                            .unwrap_or_default()
                            .to_owned()
                    };
                    (
                        None,
                        runtime
                            .plugin
                            .interfaces
                            .get(&(key("interface"), key("method")))
                            .cloned(),
                    )
                }
                _ => (None, None),
            };
            (
                runtime.init.clone(),
                command_handler,
                interface_handler,
                runtime.plugin.capabilities.clone(),
            )
        });

    match method {
        Initialize::METHOD => {
            let params: InitializeParams = from_value(params)?;
            if !crate::version::compatible(&params.api_version, PROTOCOL_VERSION) {
                return Err(ResponseError::new(
                    ErrorCode::ApiVersionMismatch,
                    format!(
                        "the plugin speaks KPP {PROTOCOL_VERSION}, the host {}",
                        params.api_version
                    ),
                ));
            }
            RUNTIME.with_borrow_mut(|runtime| {
                if let Some(runtime) = runtime {
                    runtime.init = Some(Rc::new(params));
                }
            });
            to_value(&InitializeResult {
                api_version: PROTOCOL_VERSION.to_owned(),
                plugin_capabilities: capabilities,
            })
        }
        Shutdown::METHOD => Ok(Value::Null),
        InvokeCommand::METHOD | ServiceInvoke::METHOD => {
            let Some(init) = init else {
                return Err(ResponseError::new(
                    ErrorCode::InvalidRequest,
                    "not initialized",
                ));
            };
            let context = Context { init };
            if let Some(handler) = plugin_command {
                let call: CommandCall = from_value(params)?;
                return handler(&context, call.args);
            }
            if let Some(handler) = plugin_interface {
                let call: kumiko_protocol::methods::service::ServiceInvokeParams =
                    from_value(params)?;
                return handler(&context, call.caller, call.params);
            }
            Err(ResponseError::new(
                if method == InvokeCommand::METHOD {
                    ErrorCode::NotFound
                } else {
                    ErrorCode::MethodNotFound
                },
                format!("`{method}` target is not handled by this plugin"),
            ))
        }
        _ => Err(ResponseError::new(
            ErrorCode::MethodNotFound,
            format!("unknown method `{method}`"),
        )),
    }
}

/// Exports a [`PluginMain`] as the component's `plugin` interface.
#[macro_export]
macro_rules! export_wasm_plugin {
    ($main:ty) => {
        // Native builds (workspace checks) link no component exports; the names of those
        // exports are not valid native symbols.
        #[cfg(not(target_arch = "wasm32"))]
        const _: () = {
            let _ = <$main as $crate::wasm::PluginMain>::build;
        };

        #[cfg(target_arch = "wasm32")]
        #[allow(unsafe_code)] // The export glue generated by wit-bindgen.
        mod __kumiko_plugin_export {
            use super::*;

            struct Exports;

            impl $crate::wasm::bindings::exports::kumiko::plugin::plugin::Guest for Exports {
                fn handle(
                    method: String,
                    params: String,
                ) -> Result<String, $crate::wasm::bindings::kumiko::plugin::types::RpcError> {
                    $crate::wasm::handle::<$main>(method, params)
                }

                fn on_notify(_method: String, _params: String) {}

                fn on_stream(_id: u32, _data: Vec<u8>) {}

                fn on_stream_close(_id: u32) {}
            }

            $crate::wasm::bindings::__export_kumiko_plugin!(Exports with_types_in $crate::wasm::bindings);
        }
    };
}
